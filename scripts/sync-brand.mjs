import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
const source = new URL(
    "../../presentation/layers/brand/theme.json",
    import.meta.url,
);
const target = new URL("../resources/js/brand-theme.json", import.meta.url);
if (!existsSync(source))
    throw Error(
        "Run brand synchronization from the complete Perysee workspace. Standalone builds use the committed export.",
    );
const contents = readFileSync(source, "utf8");
const theme = JSON.parse(contents);
let sharedCss = '/* Generated by application/scripts/sync-brand.mjs. */\n@theme static {\n';
for (const [name, palette] of Object.entries(theme.palettes))
    for (const [shade, value] of Object.entries(palette.shades))
        sharedCss += `--color-${name}-${shade}:${value};\n`;
sharedCss += '}\n';
for (const [mode, tokens] of Object.entries(theme.style.tokens)) {
    sharedCss += `${mode === 'light' ? ':root' : '.dark'} {\n`;
    for (const [name, value] of Object.entries(tokens)) sharedCss += `${name}:${value};\n`;
    sharedCss += '}\n';
}
// Only override explicit text utilities; variant classes must retain their own contrast.
for (const color of ['primary', 'secondary', 'success', 'info', 'warning', 'error'])
    sharedCss += `.text-${color} { color:var(--ui-text); }\n`;
sharedCss += '.brand-solid {background:var(--brand-action);color:#F8F8F8}.brand-solid:hover:not(:disabled):not([aria-disabled=true]) {background:var(--brand-action-hover)}.brand-chart {color:var(--ui-primary)}\n';
sharedCss += readFileSync(new URL('../../presentation/layers/brand/app/assets/css/surfaces.css', import.meta.url), 'utf8');
sharedCss += '.prose a, .prose a code, .prose mark {color:var(--ui-text)}\npre, pre code, pre code span {color:var(--ui-text)!important}\n';
sharedCss += '.brand-logo-light{display:block}.brand-logo-dark{display:none}.dark .brand-logo-light{display:none}.dark .brand-logo-dark{display:block}\n';
const css = '/* Generated by scripts/sync-brand.mjs. Do not edit manually. */\n@font-face{font-family:Geist;src:url(/fonts/geist-latin.woff2) format("woff2");font-weight:100 900;font-style:normal;font-display:swap}\n@theme static {--font-sans:Geist,Arial,sans-serif;}\n' + sharedCss;
const originalLogo = readFileSync(new URL('../../presentation/layers/brand/assets/logo.svg', import.meta.url), 'utf8');
const lightLogo = originalLogo;
const darkLogo = readFileSync(new URL('../../presentation/layers/brand/assets/logo-dark.svg', import.meta.url), 'utf8');
const favicon = lightLogo.replace(/(<svg[^>]*>)/, '$1\n<style>@media(prefers-color-scheme:dark){[fill="#00020C"]{fill:#F8F8F8}}</style>');
const logos = [];
for (const directory of ['../../presentation/layers/brand/public/', '../public/'])
    for (const [name, svg] of [['logo.svg', lightLogo], ['logo-dark.svg', darkLogo], ['favicon.svg', favicon]])
        logos.push([new URL(directory + name, import.meta.url), svg]);
for (const directory of ['../../presentation/layers/brand/public/', '../public/'])
    logos.push([new URL(directory + 'favicon.ico', import.meta.url), readFileSync(new URL('../../presentation/layers/brand/assets/favicon.ico', import.meta.url))]);
const version =
    JSON.stringify(
        {
            version: theme.version,
            sha256: createHash("sha256").update(contents).digest("hex"),
        },
        null,
        2,
    ) + "\n";
for (const [file, expected] of [
    ...logos,
    [new URL("../../presentation/layers/brand/app/assets/css/theme.css", import.meta.url), sharedCss],
    [target, contents],
    [new URL("../resources/css/brand.css", import.meta.url), css],
    [new URL("../resources/js/brand-version.json", import.meta.url), version],
]) {
    if (process.argv.includes("--check")) {
        if (!existsSync(file) || !readFileSync(file).equals(Buffer.from(expected)))
            throw Error(
                "Perysee application theme differs from the presentation theme. Run npm run brand:sync.",
            );
    } else writeFileSync(file, expected);
}
